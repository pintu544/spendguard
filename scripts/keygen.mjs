#!/usr/bin/env node
/**
 * SpendGuard spike — throwaway TESTNET account keygen (TASKS P1, delegated route).
 *
 * What it does, in order:
 *   1. Generates a fresh ed25519 keypair locally with near-api-js.
 *   2. Derives the NEAR **implicit** account id: the hex of the public key.
 *      An implicit account exists on-chain as soon as it is funded.
 *   3. Writes `.env` (NEAR_ACCOUNT_ID / NEAR_PRIVATE_KEY / NEAR_NETWORK=testnet)
 *      with 0600 permissions. REFUSES to overwrite an existing `.env`.
 *   4. Funds the account with 5 testnet NEAR via the docs Faucet API
 *      (POST https://docs-mcp-f18b.onrender.com/api/faucet — see SPIKE.md).
 *
 * What it prints: ONLY the account id and the funding result.
 * The private key is written to `.env` and NEVER printed, logged, or sent
 * anywhere. Keys are minted per-machine and never travel between machines.
 *
 * TESTNET ONLY. There is no mainnet path in this script by design.
 *
 * Optional: SPENDGUARD_PROXY=http://127.0.0.1:8888 routes the faucet call
 * through a proxy (same convention as src/net.ts) on networks that need one.
 */
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { KeyPairEd25519 } from "near-api-js";
import { ProxyAgent, setGlobalDispatcher } from "undici";

const FAUCET_URL = "https://docs-mcp-f18b.onrender.com/api/faucet";
const FAUCET_TIMEOUT_MS = 90_000; // the faucet host cold-starts; be patient once

async function main() {
  const envPath = resolve(process.cwd(), ".env");
  if (existsSync(envPath)) {
    console.error(
      ".env already exists — refusing to overwrite it.\n" +
        "If you want a fresh throwaway account, move the old .env aside yourself first.",
    );
    process.exit(1);
  }

  const proxy = (process.env.SPENDGUARD_PROXY ?? "").trim();
  if (proxy) setGlobalDispatcher(new ProxyAgent(proxy));

  const keyPair = KeyPairEd25519.fromRandom();
  const publicKey = keyPair.getPublicKey();
  const accountId = Buffer.from(publicKey.data).toString("hex"); // implicit id
  const privateKey = keyPair.toString(); // ed25519:... — goes to .env only, never printed

  writeFileSync(
    envPath,
    [
      "# SpendGuard spike credentials — TESTNET ONLY. Generated by scripts/keygen.mjs.",
      "# This file is gitignored and must NEVER be committed or shared.",
      `NEAR_ACCOUNT_ID=${accountId}`,
      `NEAR_PRIVATE_KEY=${privateKey}`,
      "NEAR_NETWORK=testnet",
      "",
    ].join("\n"),
    { mode: 0o600 },
  );
  console.log(`Account id (implicit): ${accountId}`);
  console.log(".env written (permissions 600). The private key is in .env only — not printed here.");

  // Fund via the docs Faucet API: 5 testnet NEAR, no key or browser needed.
  console.log("Requesting 5 testnet NEAR from the faucet…");
  try {
    const res = await fetch(FAUCET_URL, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ accountId }),
      signal: AbortSignal.timeout(FAUCET_TIMEOUT_MS),
    });
    const text = (await res.text()).trim().slice(0, 300);
    if (res.ok) {
      console.log(`Funding: OK (HTTP ${res.status})${text ? ` — ${text}` : ""}`);
    } else {
      console.log(`Funding: FAILED (HTTP ${res.status})${text ? ` — ${text}` : ""}`);
      console.log("The account + .env exist; top up later via the RUNBOOK.md fallback routes.");
    }
  } catch (err) {
    console.log(
      `Funding: FAILED (${err instanceof Error ? `${err.name}: ${err.message}` : String(err)})`,
    );
    console.log("The account + .env exist; top up later via the RUNBOOK.md fallback routes.");
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
